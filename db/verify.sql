\pset footer off

\echo '== row counts =='
SELECT 'agency' t, count(*) FROM agency
UNION ALL SELECT 'calendar', count(*) FROM calendar
UNION ALL SELECT 'stops', count(*) FROM stops
UNION ALL SELECT 'routes', count(*) FROM routes
UNION ALL SELECT 'shape_points', count(*) FROM shape_points
UNION ALL SELECT 'shapes', count(*) FROM shapes
UNION ALL SELECT 'trips', count(*) FROM trips
UNION ALL SELECT 'stop_times', count(*) FROM stop_times
ORDER BY 1;

\echo ''
\echo '== snapshot =='
SELECT snapshot_id, label, feed_version, feed_start, feed_end FROM feed_snapshot;

\echo ''
\echo '== are the published shape distances actually metres? =='
-- declared_m is max(shape_dist_traveled) from the feed.
-- geodesic_m is what PostGIS measures on the WGS84 spheroid.
SELECT
  round(min(declared_m / nullif(geodesic_m, 0))::numeric, 3) AS ratio_min,
  round(percentile_cont(0.5) WITHIN GROUP (ORDER BY declared_m / nullif(geodesic_m, 0))::numeric, 3) AS ratio_p50,
  round(max(declared_m / nullif(geodesic_m, 0))::numeric, 3) AS ratio_max,
  count(*) FILTER (WHERE abs(declared_m / nullif(geodesic_m, 0) - 1) > 0.02) AS off_by_gt_2pct
FROM shapes;

\echo ''
\echo '== times past midnight survived the integer encoding =='
SELECT count(*) AS rows_past_24h,
       max(arrival_s) AS max_arrival_s,
       (max(arrival_s) / 3600) || ':' || lpad(((max(arrival_s) % 3600) / 60)::text, 2, '0') AS max_as_clock
FROM stop_times WHERE arrival_s >= 86400;

\echo ''
\echo '== direction tag derived from route names =='
SELECT coalesce(direction_tag, '(neither)') AS tag, count(*)
FROM routes GROUP BY 1 ORDER BY 2 DESC;

\echo ''
\echo '== the primary screen: next departures from one stop =='
-- Rohini Sec 22 Terminal, after 08:00. This is the query shape the app needs.
SELECT r.route_short_name,
       r.route_desc,
       (st.departure_s / 3600) || ':' || lpad(((st.departure_s % 3600) / 60)::text, 2, '0') AS departs,
       st.stop_sequence
FROM stop_times st
JOIN trips  t ON t.snapshot_id = st.snapshot_id AND t.trip_id  = st.trip_id
JOIN routes r ON r.snapshot_id = t.snapshot_id  AND r.route_id = t.route_id
WHERE st.stop_id = '1' AND st.departure_s >= 8 * 3600
ORDER BY st.departure_s
LIMIT 8;

\echo ''
\echo '== stops within 500 m of Connaught Place =='
SELECT stop_id, stop_name,
       round(ST_Distance(geom::geography,
                         ST_SetSRID(ST_MakePoint(77.2167, 28.6315), 4326)::geography)::numeric, 0) AS metres
FROM stops
WHERE ST_DWithin(geom::geography,
                 ST_SetSRID(ST_MakePoint(77.2167, 28.6315), 4326)::geography, 500)
ORDER BY metres
LIMIT 8;

\echo ''
\echo '== implied average speed of the fabricated timetable =='
-- OTD states stop_times are generated by assuming a constant speed.
-- If that is true, this distribution should be suspiciously narrow.
WITH trip_speed AS (
  SELECT t.trip_id,
         s.declared_m / 1000.0 AS km,
         (t.end_s - t.start_s) / 3600.0 AS hours
  FROM trips t
  JOIN shapes s ON s.snapshot_id = t.snapshot_id AND s.shape_id = t.shape_id
  WHERE t.end_s > t.start_s
)
SELECT round(percentile_cont(0.05) WITHIN GROUP (ORDER BY km / hours)::numeric, 2) AS kmh_p05,
       round(percentile_cont(0.50) WITHIN GROUP (ORDER BY km / hours)::numeric, 2) AS kmh_p50,
       round(percentile_cont(0.95) WITHIN GROUP (ORDER BY km / hours)::numeric, 2) AS kmh_p95,
       count(DISTINCT round((km / hours)::numeric, 1)) AS distinct_speeds_1dp
FROM trip_speed;
