-- How often each route actually turns up at each place.
--
--   psql -f /db/schema_place_frequency.sql
--   (needs stop_place and observed_stop_passage)
--
-- WHY THIS MATTERS MORE THAN IT SOUNDS
--
-- A journey is walk + wait + ride, and the wait is often the biggest part
-- of it. Without it, journeys get ranked by ride time, which gives the
-- wrong answer. Measured on a real pair:
--
--   route 2433 - ride 5.3 min, comes every 6.4 min -> 8.5 min total
--   route 2417 - ride 4.6 min, comes every 10.7 min -> 10.0 min total
--
-- Route 2417 has the FASTER RIDE and is the WORSE JOURNEY. Only total time
-- ranks correctly, and computing it needs this table.
--
-- Built from observed passages, not the published timetable. OTD's own
-- documentation says its times are "a rough estimate generated by assuming
-- a constant speed of travel" (AGENTS.md section 2), so it cannot answer
-- how often a bus really comes. This can: 9.73 million real passages.
--
-- days_seen is carried deliberately. A frequency computed from one day is
-- not the same claim as one computed from five, and the app must be able
-- to say so rather than printing "every 7 min" with false confidence.

\set ON_ERROR_STOP on
\timing on

DROP TABLE IF EXISTS place_route_frequency;

CREATE TABLE place_route_frequency AS
SELECT
    sp.place_id,
    o.route_id,
    -- Delhi local time, matching how the travel-time model buckets hours
    -- (see compute_travel_times.sql). Reading these in UTC would put the
    -- evening peak in the wrong bucket.
    extract(hour FROM o.passage_time AT TIME ZONE 'Asia/Kolkata')::int AS hour_of_day,
    CASE WHEN extract(dow FROM (o.passage_time AT TIME ZONE 'Asia/Kolkata')::date) IN (0,6)
         THEN 'weekend' ELSE 'weekday' END AS day_type,
    count(*)                       AS passages,
    count(DISTINCT o.day)          AS days_seen,
    -- Average gap between buses, in minutes: the hour is spread across
    -- however many days were observed, so passages/days is buses per hour.
    round((60.0 / (count(*)::numeric / count(DISTINCT o.day)))::numeric, 1) AS avg_gap_minutes
FROM observed_stop_passage o
JOIN stop_place sp ON sp.stop_id = o.stop_id
GROUP BY 1, 2, 3, 4;

ALTER TABLE place_route_frequency
  ADD PRIMARY KEY (place_id, route_id, hour_of_day, day_type);

CREATE INDEX idx_prf_lookup
  ON place_route_frequency (place_id, day_type, hour_of_day);

ANALYZE place_route_frequency;

COMMENT ON TABLE place_route_frequency IS
  'How often each route was actually observed at each place, by hour and day type. Built from 9.73M real passages, not the published timetable (which OTD documents as generated by assuming constant speed).';
COMMENT ON COLUMN place_route_frequency.days_seen IS
  'How many distinct days this rests on. 1-2 days is weak evidence; the app must label it rather than presenting it as settled.';
COMMENT ON COLUMN place_route_frequency.avg_gap_minutes IS
  'Average minutes between buses on this route at this place, this hour. Typical WAIT is about half this, assuming a passenger arrives at random.';

\echo ''
\echo 'frequency table built:'
SELECT count(*) AS rows,
       count(DISTINCT place_id) AS places,
       count(*) FILTER (WHERE days_seen >= 3) AS cells_on_3plus_days,
       round(100.0 * count(*) FILTER (WHERE days_seen >= 3) / count(*), 1) AS pct_solid
FROM place_route_frequency;

\echo ''
\echo 'sanity - service by hour on weekdays (should peak morning and evening):'
SELECT hour_of_day AS delhi_hour,
       count(DISTINCT place_id) AS places_served,
       round(avg(avg_gap_minutes), 1) AS avg_gap_min
FROM place_route_frequency
WHERE day_type = 'weekday' AND days_seen >= 3
GROUP BY hour_of_day
HAVING count(*) > 500
ORDER BY hour_of_day;
